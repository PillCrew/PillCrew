  // answers travel, and `aiTest` is the settings list's "Test" button.
  aiAsk: call('ai:ask'),
  // The chip data comes from the main process: the renderer asks for a kind and gets the app's own numbers.
  aiContext: call('ai:context'),
  aiModels: call('ai:models'),
