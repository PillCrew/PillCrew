  incineratorBurn: call('inc:burn'),
  openExternal: call('open:external'),
  diagCheck: call('diag:check'),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onPositions: (cb) => ipcRenderer.on('positions', (_e, list) => cb(list)),
  onLog: (cb) => ipcRenderer.on('log', (_e, l) => cb(l)),
  onBump: (cb) => ipcRenderer.on('bump:state', (_e, s) => cb(s)),
  // A tap on Pilly's bubble brings the window forward on the Chat tab — the alert is only useful if it goes somewhere.
